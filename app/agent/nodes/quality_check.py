"""Quality check node — evaluates draft response quality before sending.

Calls Gemini 2.5 Flash as an internal reviewer to score the draft response
on relevance, completeness, tone, and groundedness. Returns a quality_score
(0-1) that drives the route_by_quality routing decision.
"""

from langchain_google_genai import ChatGoogleGenerativeAI
from pydantic import BaseModel, Field

from app.agent.state import AgentState
from app.config import settings

QUALITY_CHECK_SYSTEM_PROMPT = """\
You are an internal quality reviewer for a customer support system.

You will receive three inputs:
1. The customer's original message
2. The knowledge base context that was retrieved
3. The draft response generated by the support agent

Evaluate the draft response on four criteria, each scored from 0.0 to 1.0:

1. **Relevance** — Does the response address the customer's actual question or concern?
2. **Completeness** — Are all aspects of the customer's message covered?
3. **Tone** — Is the response professional, polite, and appropriately empathetic?
4. **Groundedness** — Is the response strictly based on the provided context? \
Penalize any information not found in the context (hallucinations).

Then provide an **overall_score** (0.0 to 1.0) that reflects the overall quality. \
A score of 0.7 or higher means the response is acceptable to send to the customer.

Be strict about groundedness: if the response contains claims not supported by the \
knowledge base context, the overall score should be below 0.7.

If the knowledge base context is empty or very thin, penalize completeness accordingly."""


class QualityCheckResult(BaseModel):
    """Structured output schema for quality evaluation."""

    relevance: float = Field(
        description="How relevant the response is to the customer's question (0-1)",
    )
    completeness: float = Field(
        description="How completely the response addresses all aspects of the question (0-1)",
    )
    tone: float = Field(
        description="How professional and appropriate the tone is (0-1)",
    )
    groundedness: float = Field(
        description="How well grounded in the provided context, without hallucinations (0-1)",
    )
    overall_score: float = Field(
        description="Overall quality score combining all criteria (0-1)",
    )
    reason: str = Field(
        description="Brief explanation of the quality assessment",
    )


def quality_check_node(state: AgentState) -> dict:
    """Evaluate the draft response quality using Gemini 2.5 Flash as a judge.

    Scores the draft on relevance, completeness, tone, and groundedness.
    Only the overall_score is written to state as quality_score.

    Returns:
        dict with key: quality_score (float, clamped to 0-1).
    """
    contexts_text = "\n\n---\n\n".join(state.get("retrieved_contexts", []))
    if not contexts_text:
        contexts_text = "No context was available."

    human_message = (
        f"## Customer Message\n{state['ticket_text']}\n\n"
        f"## Knowledge Base Context\n{contexts_text}\n\n"
        f"## Draft Response\n{state.get('draft_response', '')}"
    )

    llm = ChatGoogleGenerativeAI(
        model="gemini-3.8-flash",
        google_api_key=settings.GEMINI_API_KEY,
        temperature=0.0,
    )
    structured_llm = llm.with_structured_output(QualityCheckResult)

    result: QualityCheckResult = structured_llm.invoke([
        ("system", QUALITY_CHECK_SYSTEM_PROMPT),
        ("human", human_message),
    ])

    clamped_score = min(1.0, max(0.0, result.overall_score))

    return {"quality_score": clamped_score}
